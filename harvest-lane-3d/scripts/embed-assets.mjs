// Embeds the binary game assets (CC0 models and sounds, see
// docs/ASSETS.md) into a TypeScript module as base64 chunks, so the
// built game is one self-contained bundle with no runtime file
// dependencies. Run automatically by the build scripts.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const groups = [
  { dir: join(root, 'assets', 'audio'), prefix: 'audio/' },
  { dir: join(root, 'assets', 'models'), prefix: 'models/' },
];

const entries = [];
for (const { dir, prefix } of groups) {
  for (const file of readdirSync(dir).sort()) {
    const b64 = readFileSync(join(dir, file)).toString('base64');
    const chunks = [];
    for (let i = 0; i < b64.length; i += 40000) chunks.push(b64.slice(i, i + 40000));
    entries.push(`  '${prefix}${file}': [\n${chunks.map((c) => `    '${c}',`).join('\n')}\n  ],`);
  }
}

const out = `// GENERATED by scripts/embed-assets.mjs - do not edit.
// Base64 chunks of the binary assets under assets/ (CC0, docs/ASSETS.md).
export const EMBEDDED_ASSETS: Record<string, string[]> = {
${entries.join('\n')}
};
`;
mkdirSync(join(root, 'src', 'generated'), { recursive: true });
writeFileSync(join(root, 'src', 'generated', 'embeddedAssets.ts'), out);
console.log(`embedded ${entries.length} assets`);
